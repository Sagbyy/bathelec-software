import {
  REPORT_MAX_ADDITIONAL_PHOTOS,
  REPORT_PHOTO_MAX_BYTES,
} from '@repo/types';

const MANDATORY_REPORT_PHOTOS = 4;
const BASE64_EXPANSION_RATIO = 4 / 3;
const NON_PHOTO_FIELDS_ALLOWANCE_BYTES = 5 * 1024 * 1024;

export const MAX_REPORT_PHOTOS =
  MANDATORY_REPORT_PHOTOS + REPORT_MAX_ADDITIONAL_PHOTOS;

export const JSON_BODY_LIMIT_BYTES =
  Math.ceil(
    MAX_REPORT_PHOTOS * REPORT_PHOTO_MAX_BYTES * BASE64_EXPANSION_RATIO
  ) + NON_PHOTO_FIELDS_ALLOWANCE_BYTES;
